/**
 * Retrieve the parametric 3D CAD assembly metadata for any catalog category ID.
 * Falls back cleanly to `connector-housings` when `all` or an unknown ID is passed.
 */
export function getCadModelForCategory(categoryId) {
  if (categoryId && Object.prototype.hasOwnProperty.call(CAD_MODELS_BY_CATEGORY, categoryId)) {
    return CAD_MODELS_BY_CATEGORY[categoryId];
  }
  return CAD_MODELS_BY_CATEGORY["connector-housings"];
}

